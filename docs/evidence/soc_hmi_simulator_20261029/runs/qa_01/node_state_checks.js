const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('artifacts/soc_hmi_simulator_20261029/app.js', 'utf8');
const sandbox = {module: {exports: {}}, performance: {now: () => 1000}};
vm.runInNewContext(source, sandbox, {filename: 'app.js'});
const {createState, setScenario, sample, sensorView, healthView} = sandbox.module.exports;
function fresh(now = 1000) { const s = createState(now); sample(s, now); return s; }
let state = createState(10);
assert.equal(sensorView(state, 'th', 10).quality, 'UNKNOWN');
sample(state, 10);
assert.equal(sensorView(state, 'th', 10).quality, 'FRESH');
console.log('PASS UNKNOWN -> FRESH after valid local sample');
state = fresh(1000);
setScenario(state, 'stale', 1100);
assert.equal(sensorView(state, 'th', 1100).quality, 'STALE');
assert.notEqual(sensorView(state, 'th', 1100).value, null);
assert.equal(sensorView(state, 'mc', 1100).quality, 'FRESH');
console.log('PASS stale retains last value and only expires TH');
state = fresh(2000);
setScenario(state, 'fault', 2100);
assert.equal(sensorView(state, 'th', 2100).quality, 'FAULT');
assert.equal(sensorView(state, 'th', 2100).value, null);
assert.equal(healthView(state, 2100).level, 'error');
console.log('PASS sensor FAULT has no temperature value');
state = fresh(3000);
const beforeDisconnect = state.sensors.th.value;
setScenario(state, 'disconnected', 3100);
assert.equal(sensorView(state, 'th', 3100).quality, 'STALE');
assert.equal(sensorView(state, 'th', 3100).value, beforeDisconnect);
assert.equal(healthView(state, 3100).title, '模拟链路断开');
setScenario(state, 'normal', 3200);
assert.equal(sensorView(state, 'th', 3200).quality, 'STALE');
sample(state, 3201);
assert.equal(sensorView(state, 'th', 3201).quality, 'FRESH');
console.log('PASS disconnect retains stale value; recovery waits for a new sample');
state = fresh(4000);
state.history.push(...Array.from({length: 70}, () => ({th: 25, mc: 24})));
state.events.push(...Array.from({length: 10}, (_, i) => ({time: 't', text: String(i)})));
setScenario(state, 'restart', 4100);
assert.equal(state.generation, 2);
assert.equal(state.sensors.th.value, null);
assert.equal(state.sensors.mc.value, null);
assert.equal(state.history.length, 0);
assert.equal(state.events.length, 6);
assert.equal(sensorView(state, 'th', 4100).quality, 'UNKNOWN');
sample(state, 5600);
assert.equal(sensorView(state, 'th', 5600).quality, 'FRESH');
assert.equal(state.scenario, 'normal');
console.log('PASS restart clears snapshots/history, increments generation, then recovers on sample');
state = fresh(6000);
for (let i = 0; i < 100; i++) sample(state, 7000 + i);
assert.equal(state.history.length, 60);
setScenario(state, 'not-a-scenario', 8000);
assert.equal(state.scenario, 'normal');
console.log('PASS history bounded at 60; invalid scenario ignored');
